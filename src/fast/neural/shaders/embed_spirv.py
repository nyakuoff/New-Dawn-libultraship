#!/usr/bin/env python3
"""Compile the neural rendering kernels to SPIR-V and embed them as NrSpirv.inc.

The game build does not need a GLSL compiler: the generated file is committed. Run this after editing a shader
(needs glslangValidator on PATH):

    python3 libultraship/src/fast/neural/shaders/embed_spirv.py          # rewrite ../NrSpirv.inc
    python3 libultraship/src/fast/neural/shaders/embed_spirv.py --check  # fail if it is out of date
"""
import struct, subprocess, sys, tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
KERNELS = ["gemm", "block32", "attention", "vit_normalize", "vit_attention", "ops", "features", "composite"]


def compile_one(name: str) -> bytes:
    with tempfile.TemporaryDirectory() as tmp:
        out = Path(tmp) / f"{name}.spv"
        result = subprocess.run(["glslangValidator", "-V", "--target-env", "vulkan1.3", "--quiet", f"{name}.comp", "-o", str(out)],
                                cwd=HERE, capture_output=True, text=True)
        if result.returncode:
            sys.exit(f"{name}.comp:\n{result.stdout}{result.stderr}")
        return out.read_bytes()


def generate() -> str:
    lines = ["// Generated by shaders/embed_spirv.py from the .comp files beside it. Do not edit.", ""]
    for name in KERNELS:
        words = struct.unpack(f"<{len(compile_one(name)) // 4}I", compile_one(name))
        ident = "k" + "".join(part.capitalize() for part in name.split("_")) + "Spv"
        lines.append(f"inline constexpr uint32_t {ident}[] = {{")
        for i in range(0, len(words), 10):
            lines.append("    " + ", ".join(f"0x{w:08x}" for w in words[i:i + 10]) + ",")
        lines.append("};")
        lines.append("")
    return "\n".join(lines)


if __name__ == "__main__":
    target = HERE.parent / "NrSpirv.inc"
    text = generate()
    if "--check" in sys.argv:
        sys.exit(0 if target.exists() and target.read_text() == text else "NrSpirv.inc is out of date: run shaders/embed_spirv.py")
    target.write_text(text)
    print(f"wrote {target} ({len(text) // 1024} KiB)")
